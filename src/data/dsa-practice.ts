export type DsaPracticeTarget = {
  source: "leetcode" | "gfg";
  label: string;
  url: string;
  direct: boolean;
};

export function getDsaPracticeTarget(problemId: string, title: string, patternTitle: string): DsaPracticeTarget {
  const slug = leetcodeSlugs[problemId];
  if (slug) return {
    source: "leetcode",
    label: "Solve on LeetCode",
    url: `https://leetcode.com/problems/${slug}/`,
    direct: true
  };

  const query = encodeURIComponent(`${title} ${patternTitle}`);
  return {
    source: "gfg",
    label: "Find implementation on GFG",
    url: `https://www.geeksforgeeks.org/search/?q=${query}`,
    direct: false
  };
}
